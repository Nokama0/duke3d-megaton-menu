#!/usr/bin/env python3
"""Bakes Bahnschrift and Cascadia Mono into an 8-bit alpha atlas plus metrics.

Emits font_data.cpp. Requires Pillow. Run from src/duke3dmod/:
    python gen_font.py

Antialiased proportional text is the whole point: the design calls for real
typography, not the 1-bit monospace bitmap an older project used.
"""
import os
from PIL import Image, ImageFont, ImageDraw

_WINDIR = os.environ.get("WINDIR")
if not _WINDIR:
    raise SystemExit("WINDIR is not set; fonts are read from its Fonts folder")
_FONTS = os.path.join(_WINDIR, "Fonts")

FACES = [
    ("FONT_UI",    os.path.join(_FONTS, "bahnschrift.ttf"), 21),
    ("FONT_SMALL", os.path.join(_FONTS, "bahnschrift.ttf"), 16),
    ("FONT_MONO",  os.path.join(_FONTS, "CascadiaMono.ttf"), 18),
]
ATLAS_W, ATLAS_H = 512, 256
PAD = 1

def main():
    atlas = Image.new("L", (ATLAS_W, ATLAS_H), 0)
    draw = ImageDraw.Draw(atlas)
    metrics, heights = [], []
    pen_x, pen_y, row_h = PAD, PAD, 0

    for _name, path, size in FACES:
        try:
            font = ImageFont.truetype(path, size)
        except OSError:
            raise SystemExit(f"missing font: {path}. Install it or edit FACES.")
        ascent, descent = font.getmetrics()
        heights.append(ascent + descent)
        glyphs = []
        for c in range(0x20, 0x80):
            ch = chr(c)
            box = font.getbbox(ch)                       # (x0, y0, x1, y1)
            adv = int(round(font.getlength(ch)))
            if box is None or ch == " ":
                glyphs.append((0, 0, 0, 0, 0, 0, adv))
                continue
            gw, gh = box[2] - box[0], box[3] - box[1]
            if gw <= 0 or gh <= 0:
                glyphs.append((0, 0, 0, 0, 0, 0, adv))
                continue
            if pen_x + gw + PAD > ATLAS_W:
                pen_x, pen_y, row_h = PAD, pen_y + row_h + PAD, 0
            if pen_y + gh + PAD > ATLAS_H:
                raise SystemExit("atlas too small; raise ATLAS_H")
            draw.text((pen_x - box[0], pen_y - box[1]), ch, fill=255, font=font)
            glyphs.append((pen_x, pen_y, gw, gh, box[0], box[1], adv))
            pen_x += gw + PAD
            row_h = max(row_h, gh)
        metrics.append(glyphs)
        pen_x, pen_y, row_h = PAD, pen_y + row_h + PAD, 0

    data = atlas.tobytes()
    with open("font_data.cpp", "w", newline="\n") as o:
        o.write('#include "font.h"\n')
        o.write("// Generated by gen_font.py. Do not hand-edit; regenerate instead.\n")
        o.write(f"const int FONT_ATLAS_W = {ATLAS_W};\nconst int FONT_ATLAS_H = {ATLAS_H};\n")
        o.write("const int font_height[FONT_COUNT] = {%s};\n" % ",".join(str(h) for h in heights))
        o.write("const Glyph font_glyphs[FONT_COUNT][96] = {\n")
        for glyphs in metrics:
            o.write("  {" + ",".join("{%d,%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "},\n")
        o.write("};\n")
        o.write("const unsigned char font_atlas[] = {\n")
        for i in range(0, len(data), 32):
            o.write("".join("%d," % b for b in data[i:i + 32]) + "\n")
        o.write("};\n")
    print(f"wrote font_data.cpp ({len(data)} atlas bytes)")

if __name__ == "__main__":
    main()
